/*
# SaifQuiz Phase 5: Recording System

## Overview
Extends the recordings table to support the camera/microphone recording system
and creates a private Supabase Storage bucket for recording files.

## Changes to `recordings` table
- Added `status` (text, NOT NULL, default 'recording') — tracks upload state:
  recording → uploading → uploaded → failed
- Added `video_path` (text, nullable) — path to video file in Storage
- Added `audio_path` (text, nullable) — path to audio file in Storage
  (kept separate from storage_path for clarity; storage_path remains for backward compat)
- Added `file_size_bytes` (bigint, nullable) — size of uploaded recording
- Added `updated_at` (timestamptz, default now()) — for tracking upload progress
- Added CHECK constraint on status values

## Storage
- Creates bucket 'recordings' as PRIVATE (public = false)
- Files organized as: {exam_id}/{attempt_id}/video.webm and audio.webm
- Only authenticated users (admins) can read via signed URLs
- Anon can upload (students record during exam) but cannot list/read directly

## RLS on recordings table
- Existing policies remain: anon can insert/select, admin can update/delete
- No changes needed — students insert recording metadata, admins view recordings

## Important Notes
1. Recording status is tracked separately from exam attempt status.
   A failed recording upload does NOT affect the exam result.
2. The storage bucket is private — recordings are only accessible via signed URLs
   generated by admin-side code.
3. Students can upload to the bucket but cannot read other students' recordings.
*/

-- ============================================================
-- RECORDINGS: Add new columns
-- ============================================================
ALTER TABLE public.recordings ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'recording';
ALTER TABLE public.recordings ADD COLUMN IF NOT EXISTS video_path text;
ALTER TABLE public.recordings ADD COLUMN IF NOT EXISTS audio_path text;
ALTER TABLE public.recordings ADD COLUMN IF NOT EXISTS file_size_bytes bigint;
ALTER TABLE public.recordings ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

-- ============================================================
-- RECORDINGS: Add status CHECK constraint
-- ============================================================
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'recordings_status_check'
    AND conrelid = 'public.recordings'::regclass
  ) THEN
    ALTER TABLE public.recordings
      ADD CONSTRAINT recordings_status_check
      CHECK (status IN ('recording', 'uploading', 'uploaded', 'failed'));
  END IF;
END $$;

-- ============================================================
-- RECORDINGS: Add updated_at trigger
-- ============================================================
CREATE OR REPLACE FUNCTION public.handle_recording_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'recordings_updated_at') THEN
    CREATE TRIGGER recordings_updated_at
      BEFORE UPDATE ON public.recordings
      FOR EACH ROW EXECUTE FUNCTION public.handle_recording_updated_at();
  END IF;
END $$;

-- ============================================================
-- STORAGE: Create private recordings bucket
-- ============================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('recordings', 'recordings', false)
ON CONFLICT (id) DO NOTHING;

-- ============================================================
-- STORAGE POLICIES: recordings bucket
-- ============================================================
-- Students (anon) can upload files to the recordings bucket
DROP POLICY IF EXISTS "anon_upload_recordings" ON storage.objects;
CREATE POLICY "anon_upload_recordings"
  ON storage.objects FOR INSERT
  TO anon, authenticated
  WITH CHECK (bucket_id = 'recordings');

-- Authenticated users (admins) can read recordings via signed URLs
DROP POLICY IF EXISTS "authenticated_read_recordings" ON storage.objects;
CREATE POLICY "authenticated_read_recordings"
  ON storage.objects FOR SELECT
  TO authenticated
  USING (bucket_id = 'recordings');

-- Authenticated users (admins) can delete recordings
DROP POLICY IF EXISTS "authenticated_delete_recordings" ON storage.objects;
CREATE POLICY "authenticated_delete_recordings"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (bucket_id = 'recordings');

-- ============================================================
-- INDEX: recordings by attempt for quick lookup
-- ============================================================
CREATE INDEX IF NOT EXISTS idx_recordings_status ON public.recordings(status);
